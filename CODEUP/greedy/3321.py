'''
3321 : 최고의 피자

문제 설명
vega 선생님은 Miss 피자 가게의 단골 손님이다.
그는 이번 달부터 절약 생활을 시작했다.
그래서 그는 피자 가게에서 주문할 수 있는 피자 중 1 달러 당 열량이 최대가 되는 피자를 주문하고 싶어한다.
이러한 피자를 "최고의 피자"라고 부르기로 하자.
"최고의 피자"는 1종류가 아니다.
Miss 피자는 N 종류의 토핑에서 여러 종류를 자유롭게 선택하여, 도우 위에 올려 주문할 수있다.
같은 토핑을 2 개 이상 올릴 수 없다.
도우에 토핑을 하나도 하지 않은  피자도 주문할 수있다.
도우의 가격은 A 달러이며, 토핑의 가격은 모두 B 달러이다.
실제 피자 가격은 도우의 가격과 토핑 가격의 합계이다.
즉, 토핑을 k 종류 (0 ≦ k ≦ N) 한 피자의 가격은 A + k × B 원이다.
피자 전체의 칼로리는 도우 열량과 토핑 칼로리의 합계이다.
도우의 가격과 토핑의 가격, 그리고 도우와 각 토핑 열량 값이 주어 졌을 때, "최고의 피자"의 1 달러 당 열량의 수를 구하는 프로그램을 작성하시오.

입력
첫 번째 줄에는 토핑 종류 수를 나타내는 하나의 정수 N (1 ≦ N ≦ 100)이 입력된다.
두 번째 줄에는 두 개의 정수 A, B (1 ≦ A ≦ 1000,1 ≦ B ≦ 1000)가 공백을 구분으로 입력된다. A는 도우의 가격, B는 토핑의 가격을 나타낸다.
세 번째 줄에는 도우의 칼로리를 나타내는 정수 C (1 ≦ C ≦ 10000)가 입력된다.
3 + i 행 (1 ≦ i ≦ N)는 i 번째의 토핑 칼로리 수를 나타내는 정수 Di (1 ≦ Di ≦ 10,000)가 입력된다.

출력
"최고의 피자" 1 달러 당 열량의 수를 소수점 이하는 버리고 정수로 출력한다.
'''

# ------------------------------------------------------------
# 로컬 테스트용 입력 파일 연결 - codex로 생성
# ------------------------------------------------------------
import os
import sys


# __file__은 현재 실행 중인 파이썬 파일의 경로를 의미한다.
# os.path.dirname(__file__)은 이 파일(3321.py)이 들어 있는 폴더 경로를 구한다.
# 즉, 아래 코드는 "3321.py와 같은 폴더에 있는 input.txt"의 전체 경로를 만든다.
input_path = os.path.join(os.path.dirname(__file__), "input.txt")

# input.txt 파일이 실제로 존재할 때만 실행된다.
# sys.stdin은 input()이 데이터를 읽어오는 기본 입력 통로다.
# 이 값을 input.txt 파일로 바꾸면, 아래의 input()들은 키보드 입력을 기다리지 않고
# input.txt에 적힌 내용을 위에서부터 한 줄씩 읽는다.
#
# CodeUp에 제출할 때는 서버에 내 input.txt 파일이 없으므로 이 if문은 실행되지 않는다.
# 그래서 제출 환경에서는 원래처럼 CodeUp이 주는 표준 입력을 input()으로 읽게 된다.
if os.path.exists(input_path):
    sys.stdin = open(input_path, "r", encoding="utf-8")



# ------------------------------------------------------------
# 코드 
# ------------------------------------------------------------
import math

n = int(input())
d, t = map(int, input().split())
dc = int(input())
tc = [int(input()) for _ in range(n)]

total = dc
cal = dc / d

tc.sort(reverse=True)  # 칼로리가 높은 토핑부터 넣어 보려고 내림차순 정렬한다.
for i in range(n):
    total += tc[i]
    new_cal = total / (d + (i + 1) * t)
    if cal < new_cal:
        cal = new_cal
    else:
        break

print(math.floor(cal))